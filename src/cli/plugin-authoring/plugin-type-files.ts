import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { basename, dirname, join } from 'node:path'
import { isPluginSourceModulePath } from '../../shared/plugins/frames/plugin-frame-source-modules'
import { parsePluginManifest } from '../../shared/plugins/manifest/plugin-manifest'

/** Plugin-relative folder `occ plugin types` owns; dev hashing and loading skip it. */
export const PLUGIN_TYPES_DIR = '.occ/types'

/** Host, frame (`window.occ`), worker (`occ/worker`) and test kit (`occ/testing`) typings,
 *  under resources/plugins/types. */
const PLUGIN_SURFACE_TYPINGS = [
  { dir: 'occ-host', file: 'occ-host.d.ts' },
  { dir: 'occ-frame', file: 'occ-frame.d.ts' },
  { dir: 'occ-worker', file: 'occ-worker.d.ts' },
  { dir: 'occ-services', file: 'occ-services.d.ts' },
  { dir: 'occ-testing', file: 'occ-testing.d.ts' }
] as const

// Why one tsconfig the plugin extends: the typings and JSX settings then track the OCC that wrote
// them, and a plugin's own `include` cannot drop them (typeRoots resolve against this file).
const TYPES_TSCONFIG = {
  compilerOptions: {
    strict: true,
    noEmit: true,
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'Bundler',
    allowImportingTsExtensions: true,
    isolatedModules: true,
    jsx: 'react-jsx',
    jsxImportSource: 'occ',
    lib: ['ES2022', 'DOM'],
    // tsc 7 reaches `occ` via the symlinked path and the typeRoots via the realpath, so a plugin
    // under a symlink (macOS /tmp) loads the typings twice (TS2300 duplicate identifiers).
    preserveSymlinks: true,
    typeRoots: ['.'],
    types: ['occ', ...PLUGIN_SURFACE_TYPINGS.map(({ dir }) => dir)]
  }
}

/** The `occ` module's typings, split by size; written as one `occ/index.d.ts`. */
export const OCC_MODULE_TYPINGS = [
  'occ.d.ts',
  'occ-components.d.ts',
  'occ-components-layout.d.ts',
  'occ-components-data.d.ts'
] as const

const GENERATED_NOTE =
  '// Written by `occ plugin types`; regenerated by `occ plugin dev load`. Do not edit.\n'

/** Packaged apps ship typings as extraResources at <Resources>/plugins; dev: resources/plugins. */
function defaultTypingsRoot(): string {
  const appRoot = join(__dirname, '..', '..', '..')
  return basename(appRoot) === 'app.asar.unpacked'
    ? join(dirname(appRoot), 'plugins')
    : join(appRoot, 'resources', 'plugins')
}

async function readOCCPluginTypings(typingsRoot: string): Promise<string> {
  const parts = await Promise.all(
    OCC_MODULE_TYPINGS.map((file) => readFile(join(typingsRoot, 'declarative', file), 'utf8'))
  )
  return parts.join('\n')
}

/** Every typings file `occ plugin types` writes, keyed by its `.occ/types` folder. */
export async function readOCCAuthorTypings(): Promise<Record<string, string>> {
  const typingsRoot = defaultTypingsRoot()
  const typings: Record<string, string> = { occ: await readOCCPluginTypings(typingsRoot) }
  for (const { dir, file } of PLUGIN_SURFACE_TYPINGS) {
    typings[dir] = await readFile(join(typingsRoot, 'types', file), 'utf8')
  }
  return typings
}

/** Writes `.occ/types/<folder>/index.d.ts` per typings file, a `tsconfig.json` listing them, and
 *  a `.gitignore` that ignores `.occ/`. */
export async function writePluginTypeFiles(pluginDir: string): Promise<string[]> {
  const typings = await readOCCAuthorTypings()
  const files: Record<string, string> = { '.occ/.gitignore': '*\n' }
  for (const [dir, text] of Object.entries(typings)) {
    await mkdir(join(pluginDir, '.occ', 'types', dir), { recursive: true })
    files[`${PLUGIN_TYPES_DIR}/${dir}/index.d.ts`] = GENERATED_NOTE + text
  }
  files[`${PLUGIN_TYPES_DIR}/tsconfig.json`] = `${JSON.stringify(TYPES_TSCONFIG, null, 2)}\n`
  for (const [file, content] of Object.entries(files)) {
    await writeFile(join(pluginDir, ...file.split('/')), content)
  }
  return Object.keys(files)
}

/** A folder gets typings on dev load when it has them, its tsconfig wants them, or it has a
 *  TS/TSX entry or a components panel. */
export async function pluginFolderWantsTypes(pluginDir: string): Promise<boolean> {
  if (existsSync(join(pluginDir, '.occ', 'types'))) {
    return true
  }
  const tsconfig = await readFile(join(pluginDir, 'tsconfig.json'), 'utf8').catch(() => '')
  if (tsconfig.includes(PLUGIN_TYPES_DIR)) {
    return true
  }
  const raw = await readFile(join(pluginDir, 'occ-plugin.json'), 'utf8').catch(() => null)
  let parsed: unknown = null
  try {
    parsed = raw === null ? null : JSON.parse(raw)
  } catch {
    return false
  }
  const manifest = parsePluginManifest(parsed)
  if (!manifest.ok) {
    return false
  }
  const { panels, customEditors } = manifest.manifest.contributes
  return (
    panels.some((panel) => panel.ui === 'components') ||
    [...panels, ...customEditors].some((item) => isPluginSourceModulePath(item.entry))
  )
}
