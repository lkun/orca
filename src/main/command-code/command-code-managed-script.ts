import { posixCurlCommand } from '../agent-hooks/hook-post-command'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      'if "%OCC_AGENT_HOOK_PORT%"=="" if defined OCC_AGENT_HOOK_ENDPOINT if exist "%OCC_AGENT_HOOK_ENDPOINT%" call "%OCC_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%OCC_AGENT_HOOK_TOKEN%"=="" if not "%OCC_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\occ-dev\\agent-hooks" for /r "%APPDATA%\\occ-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      // Per-worktree `pnpm dev` profiles live one level down; FOR /R cannot take a FOR variable as its root.
      'if "%OCC_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\occ-dev-wt" for /d %%P in ("%APPDATA%\\occ-dev-wt\\*") do call :scanEndpointDir "%%~fP\\agent-hooks"',
      'if "%OCC_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\occ\\agent-hooks" for /r "%APPDATA%\\occ\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':scanEndpointDir',
      'if not "%OCC_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'if exist "%~1" for /r "%~1" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%OCC_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set OCC_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%OCC_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__occ_read_ancestor_var() {',
    '  __occ_name="$1"',
    '  __occ_pid="${PPID:-}"',
    '  while [ -n "$__occ_pid" ] && [ "$__occ_pid" != "0" ] && [ "$__occ_pid" != "1" ]; do',
    '    __occ_value=""',
    '    if [ -r "/proc/$__occ_pid/environ" ]; then',
    '      __occ_value=$(tr "\\000" "\\n" < "/proc/$__occ_pid/environ" 2>/dev/null | sed -n "s/^${__occ_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -z "$__occ_value" ]; then',
    '      __occ_value=$(ps eww -p "$__occ_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n "s/^${__occ_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -n "$__occ_value" ]; then',
    '      printf "%s\\n" "$__occ_value"',
    '      return 0',
    '    fi',
    '    __occ_pid=$(ps -o ppid= -p "$__occ_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__occ_fill_from_ancestor() {',
    '  __occ_name="$1"',
    '  case "$__occ_name" in',
    '    OCC_AGENT_HOOK_ENDPOINT) [ -z "${OCC_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    OCC_AGENT_HOOK_PORT) [ -z "${OCC_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    OCC_AGENT_HOOK_TOKEN) [ -z "${OCC_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    OCC_AGENT_HOOK_ENV) [ -z "${OCC_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    OCC_AGENT_HOOK_VERSION) [ -z "${OCC_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    OCC_PANE_KEY) [ -z "${OCC_PANE_KEY:-}" ] || return 0 ;;',
    '    OCC_TAB_ID) [ -z "${OCC_TAB_ID:-}" ] || return 0 ;;',
    '    OCC_WORKTREE_ID) [ -z "${OCC_WORKTREE_ID:-}" ] || return 0 ;;',
    '    OCC_AGENT_LAUNCH_TOKEN) [ -z "${OCC_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __occ_value=$(__occ_read_ancestor_var "$__occ_name") || return 0',
    '  [ -n "$__occ_value" ] && export "$__occ_name=$__occ_value"',
    '}',
    '__occ_endpoint_value() {',
    '  __occ_endpoint_name="$1"',
    '  __occ_endpoint_path="$2"',
    '  sed -n "s/^${__occ_endpoint_name}=//p" "$__occ_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__occ_fill_from_endpoint_file() {',
    '  __occ_endpoint_path="$1"',
    '  [ -r "$__occ_endpoint_path" ] || return 0',
    '  __occ_endpoint_port=$(__occ_endpoint_value OCC_AGENT_HOOK_PORT "$__occ_endpoint_path")',
    '  if [ -n "${OCC_AGENT_HOOK_PORT:-}" ] && [ -n "$__occ_endpoint_port" ] && [ "$__occ_endpoint_port" != "$OCC_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __occ_endpoint_name in OCC_AGENT_HOOK_PORT OCC_AGENT_HOOK_TOKEN OCC_AGENT_HOOK_ENV OCC_AGENT_HOOK_VERSION; do',
    '    eval "__occ_current=\\${$__occ_endpoint_name:-}"',
    '    [ -z "$__occ_current" ] || continue',
    '    __occ_endpoint_value=$(__occ_endpoint_value "$__occ_endpoint_name" "$__occ_endpoint_path")',
    '    [ -n "$__occ_endpoint_value" ] && export "$__occ_endpoint_name=$__occ_endpoint_value"',
    '  done',
    '}',
    '# Recover pane/hook metadata from the parent TUI after Command Code sanitizes hook env.',
    'for __occ_name in OCC_AGENT_HOOK_ENDPOINT OCC_AGENT_HOOK_PORT OCC_AGENT_HOOK_TOKEN OCC_AGENT_HOOK_ENV OCC_AGENT_HOOK_VERSION OCC_PANE_KEY OCC_TAB_ID OCC_WORKTREE_ID OCC_AGENT_LAUNCH_TOKEN; do',
    '  __occ_fill_from_ancestor "$__occ_name"',
    'done',
    'if [ -n "$OCC_AGENT_HOOK_ENDPOINT" ] && [ -r "$OCC_AGENT_HOOK_ENDPOINT" ]; then',
    '  __occ_fill_from_endpoint_file "$OCC_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Recover stripped token metadata by matching the preserved loopback port.',
    'if [ -z "$OCC_AGENT_HOOK_TOKEN" ] && [ -n "$OCC_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/occ-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/occ-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/occ-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/occ-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/occ-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/occ-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/occ/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/occ/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^OCC_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$OCC_AGENT_HOOK_PORT" ]; then',
    '      __occ_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$OCC_AGENT_HOOK_PORT" ] || [ -z "$OCC_AGENT_HOOK_TOKEN" ] || [ -z "$OCC_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Bound stalled posts and pipe large payloads through stdin to avoid EDR command-line false positives.
    `printf '%s' "$payload" | ${posixCurlCommand()} -sS -X POST "http://127.0.0.1:\${OCC_AGENT_HOOK_PORT}/hook/command-code" \\`,
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-OCC-Agent-Hook-Token: ${OCC_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${OCC_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${OCC_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${OCC_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${OCC_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${OCC_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${OCC_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
